import { join } from "node:path";
import { writeFile } from "node:fs/promises";
import { auditDir, ensureDir } from "../storage/fs";
import { loadConversation } from "../storage/conversations";
import { getAuditReport, findAuditById } from "../storage/audits";
import type { Audit, AuditReport, ChatMessage } from "../report/schema";

export type SessionExport = {
  audit_id: string;
  company_slug: string;
  filename: string;
  md_path: string;
  html_path: string;
  message_count: number;
  done_count: number;
};

export async function exportSession(auditId: string): Promise<SessionExport> {
  const audit = await findAuditById(auditId);
  if (!audit) throw new Error(`Audit not found: ${auditId}`);
  const report = await getAuditReport(audit.company_slug, audit.id);
  if (!report) throw new Error("Report missing");
  const conversation = await loadConversation(audit.company_slug, audit.id);

  const ts = new Date().toISOString().replace(/[:.]/g, "-");
  const slug = `${ts}.md`;
  const dir = join(auditDir(audit.company_slug, audit.id), "sessions");
  await ensureDir(dir);

  const md = renderMarkdown(audit, report, conversation.messages);
  const html = renderHtml(audit, report, conversation.messages, md);

  const mdPath = join(dir, slug);
  const htmlPath = mdPath.replace(/\.md$/, ".html");
  await writeFile(mdPath, md, "utf8");
  await writeFile(htmlPath, html, "utf8");

  return {
    audit_id: audit.id,
    company_slug: audit.company_slug,
    filename: slug.replace(/\.md$/, ""),
    md_path: mdPath,
    html_path: htmlPath,
    message_count: conversation.messages.length,
    done_count:
      (report.todo_list ?? []).filter((t) => t.status === "done").length +
      (report.implementation_plan ?? []).filter((p) => p.completed).length,
  };
}

function renderMarkdown(
  audit: Audit,
  report: AuditReport,
  messages: ChatMessage[],
): string {
  const lines: string[] = [];
  lines.push(`# Session report — ${report.site_name}`);
  lines.push("");
  lines.push(`- **URL:** ${report.source_value}`);
  lines.push(`- **Audit ID:** ${audit.id}`);
  lines.push(`- **Audit generated:** ${report.generated_at}`);
  lines.push(`- **Session exported:** ${new Date().toISOString()}`);
  lines.push("");
  lines.push("## Scores");
  lines.push("");
  lines.push(`- Overall: **${report.site_overall_score}** / 100`);
  lines.push(`- SEO:     **${report.site_seo_score}** / 100`);
  lines.push(`- GEO:     **${report.site_geo_score}** / 100`);
  lines.push(`- Pages audited: ${report.pages_audited}`);
  lines.push("");

  const doneTodos = (report.todo_list ?? []).filter(
    (t) => t.status === "done",
  );
  const openCritical = (report.todo_list ?? []).filter(
    (t) => (t.status ?? "open") !== "done" && t.severity === "critical",
  );
  const donePlan = (report.implementation_plan ?? []).filter((p) => p.completed);

  lines.push("## Actions taken this session");
  lines.push("");
  if (doneTodos.length === 0 && donePlan.length === 0) {
    lines.push("_No items marked done yet._");
  } else {
    if (doneTodos.length) {
      lines.push("**Closed TO-DO items:**");
      for (const t of doneTodos) lines.push(`- [x] ${t.id}: ${t.issue}`);
      lines.push("");
    }
    if (donePlan.length) {
      lines.push("**Completed implementation plan items:**");
      for (const p of donePlan)
        lines.push(`- [x] ${p.id}: ${p.action} (${p.priority})`);
      lines.push("");
    }
  }

  lines.push("## Open critical items");
  lines.push("");
  if (openCritical.length === 0) {
    lines.push("_None outstanding._");
  } else {
    for (const t of openCritical) {
      lines.push(`- [ ] **${t.id}** ${t.issue}`);
      lines.push(`  - Fix: ${t.fix}`);
    }
  }
  lines.push("");

  lines.push("## Q&A transcript");
  lines.push("");
  if (messages.length === 0) {
    lines.push("_No questions asked yet._");
  } else {
    for (const m of messages) {
      const who = m.role === "user" ? "You" : "Claude";
      lines.push(`### ${who} — ${m.created_at}`);
      lines.push("");
      lines.push(m.content);
      lines.push("");
    }
  }

  lines.push("---");
  lines.push("Generated by SEO Audit Studio");
  return lines.join("\n");
}

